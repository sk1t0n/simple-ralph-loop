#!/bin/bash

# Проверяем, передан ли аргумент с файлом
if [ -z "$1" ]; then
  echo "Ошибка: Не указан файл с задачами!"
  echo "Использование: $0 <путь_к_файлу.txt>"
  exit 1
fi

TASK_FILE="$1"
LOG_FILE="progress.txt"

# Проверяем существование файла с задачами
if [ ! -f "$TASK_FILE" ]; then
  echo "Ошибка: Файл '$TASK_FILE' не найден!"
  exit 1
fi

# Очищаем или создаем файл лога перед началом работы
echo "=== Старт выполнения задач $(date) ===" >"$LOG_FILE"
echo >>"$LOG_FILE"

# Читаем файл построчно
while IFS= read -r PROMPT; do
  # Пропускаем пустые строки
  if [ -z "$PROMPT" ]; then
    continue
  fi

  # Выводим инфо в терминал
  echo "------------------------------------------------------"
  echo "Запуск задачи: $PROMPT"
  echo "------------------------------------------------------"

  # Временный файл для перехвата вывода команды opencode
  TMP_OUTPUT=$(mktemp)

  # Получаем время начала выполнения задачи в секундах (Unix Epoch)
  sec1=$(date +%s)

  # Запускаем opencode, дублируя вывод в терминал и во временный файл
  opencode run "$PROMPT" </dev/null 2>&1 | tee "$TMP_OUTPUT"

  # Получаем время окончания выполнения задачи в секундах (Unix Epoch)
  sec2=$(date +%s)

  # Считаем общую разницу в секундах
  diff=$((sec2 - sec1))

  # Раскладываем секунды на часы, минуты и секунды
  hours=$((diff / 3600))
  minutes=$(((diff % 3600) / 60))
  seconds=$((diff % 60))

  # Сохраняем код завершения команды
  STATUS=${PIPESTATUS[0]}

  # Записываем результат выполнения в лог-файл
  {
    echo "------------------------------------------------------"
    echo "Задача: $PROMPT"
    echo "------------------------------------------------------"
    echo
    echo "Время выполнения задачи: $hours ч., $minutes мин., $seconds сек."
    echo "Вывод команды:"
    cat "$TMP_OUTPUT"
    echo
  } >>"$LOG_FILE"

  # Проверяем успешность выполнения
  if [ $STATUS -ne 0 ]; then
    echo -e "[ОШИБКА] Команда opencode завершилась неудачно со статусом $STATUS!" | tee -a "$LOG_FILE"
    echo "Выполнение скрипта прервано." | tee -a "$LOG_FILE"
    rm -f "$TMP_OUTPUT"
    exit $STATUS
  fi

  # Пишем разделитель в лог и терминал, если всё успешно
  echo -e "Задача успешно выполнена.\n------------------------------------------------------\n" >>"$LOG_FILE"
  echo -e "\nЗадача успешно выполнена."
  echo -e "Время выполнения задачи: $hours ч., $minutes мин., $seconds сек."
  echo -e "------------------------------------------------------\n"

  rm -f "$TMP_OUTPUT"

done <"$TASK_FILE"

echo "Все задачи успешно выполнены! Лог сохранен в $LOG_FILE."
